/* =====================================================================
   Application tracker: localStorage, optionally synced to a GitHub file
   ===================================================================== */
const tracker = {
  apps: {},        // id -> application (deleted ones keep a tombstone); loaded from the vault after unlock
  list() { return Object.values(this.apps).filter(a => !a.deleted); },
  get(id) { const a = this.apps[id]; return a && !a.deleted ? a : null; },
  save(app) {
    app.updated_at = new Date().toISOString();
    this.apps[app.id] = app;
    vault.data.applications = this.apps; vault.save();
    sync.schedule();
    $("app-count").textContent = this.list().length ? `(${this.list().length})` : "";
  },
  setStatus(id, status, job) {
    let app = this.get(id);
    if (!status) { if (app) this.save({ id, deleted: true }); return; }
    if (!app) {
      app = { id, company: job.company, title: job.title, location: job.location, url: job.url,
              apply_url: job.apply_url || job.url, role: roleOf(job), notes: "", history: [] };
    }
    if (app.status !== status) app.history = [...(app.history || []), { status, at: new Date().toISOString() }];
    app.status = status;
    if (status === "applied" && !app.applied_on) app.applied_on = today();
    this.save(app);
  },
  merge(remote) {  // newest edit per id wins, so two devices can both make changes
    let changed = false;
    for (const raw of remote || []) {
      const r = sanitizeApp(raw); if (!r) continue;
      const l = this.apps[r.id];
      if (!l || (r.updated_at || "") > (l.updated_at || "")) { this.apps[r.id] = r; changed = true; }
    }
    vault.data.applications = this.apps; vault.save();
    return changed;
  },
  file() { return { applications: Object.values(this.apps), updated: new Date().toISOString() }; },
};

const sync = {
  cfg: null, sha: null, timer: null,
  status(text, cls = "") { $("sync-status").innerHTML = `<span class="${cls}">${esc(text)}</span>`; },
  valid(c) {
    return /^[\w.-]+\/[\w.-]+$/.test(c.repo) && /^[\w.\/-]+\.json$/.test(c.path) && !c.path.split("/").includes("..")
      && /^[\w.\/-]*$/.test(c.branch) && /^(github_pat_|ghp_)[\w]+$/.test(c.token);
  },
  api(query = "") {
    const c = this.cfg, path = c.path.replace(/^\/+/, "").split("/").map(encodeURIComponent).join("/");
    return `https://api.github.com/repos/${c.repo}/contents/${path}${query}`;  // the token only ever goes to api.github.com
  },
  headers() { return { Authorization: `Bearer ${this.cfg.token}`, Accept: "application/vnd.github+json" }; },
  async pull() {
    if (!this.cfg) { this.status("Saved in this browser only"); return; }
    this.status("Syncing…");
    try {
      const r = await fetch(this.api(this.cfg.branch ? `?ref=${encodeURIComponent(this.cfg.branch)}` : ""),
                            { headers: this.headers(), cache: "no-store" });
      if (r.status === 404) { this.sha = null; await this.push(); return; }
      if (!r.ok) throw new Error(`GitHub ${r.status}`);
      const body = await r.json();
      this.sha = body.sha;
      let remote = JSON.parse(new TextDecoder().decode(b64.dec(body.content.replace(/\n/g, ""))));
      let legacyPlain = false;
      if (remote.ct) {
        if (vault.plaintext) throw new Error("file is encrypted; open the published site instead");
        if (remote.salt !== vault.salt) throw new Error("file was encrypted for a different site password");
        remote = await vault.decrypt(remote);
      } else legacyPlain = true;
      tracker.merge(remote.applications);
      const remoteIds = new Set((remote.applications || []).map(a => a.id + a.updated_at));
      const localAhead = Object.values(tracker.apps).some(a => !remoteIds.has(a.id + a.updated_at));
      if (localAhead || (legacyPlain && !vault.plaintext)) await this.push(); else this.status(`Synced ${new Date().toLocaleTimeString()}`, "sync-ok");
      renderAll();
    } catch (e) { this.status(`Sync failed: ${e.message}`, "sync-err"); }
  },
  async push() {
    if (!this.cfg) return;
    // the synced file is encrypted with the site key, so it is safe even in a public repo
    const payload = vault.plaintext ? tracker.file() : await vault.encrypt(tracker.file());
    const json = JSON.stringify(payload, null, 1) + "\n";
    const content = btoa(Array.from(new TextEncoder().encode(json), b => String.fromCharCode(b)).join(""));
    const body = { message: "Update job applications", content, ...(this.sha ? { sha: this.sha } : {}),
                   ...(this.cfg.branch ? { branch: this.cfg.branch } : {}) };
    const r = await fetch(this.api(), { method: "PUT", headers: this.headers(), body: JSON.stringify(body) });
    if (r.status === 409 || r.status === 422) { await this.pull(); return; }  // edited elsewhere: merge, retry
    if (!r.ok) { this.status(`Sync failed: GitHub ${r.status}`, "sync-err"); return; }
    this.sha = (await r.json()).content.sha;
    this.status(`Synced ${new Date().toLocaleTimeString()}`, "sync-ok");
  },
  schedule() {
    if (!this.cfg) return;
    clearTimeout(this.timer);
    this.status("Unsaved changes…");
    this.timer = setTimeout(() => this.push().catch(e => this.status(`Sync failed: ${e.message}`, "sync-err")), 1500);
  },
};

