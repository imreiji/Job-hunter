function lineChart(el, dates, series) {  // series: [{key,label,color,values}]
  const W = Math.max(320, el.clientWidth || 600), H = 240, m = { t: 12, r: 104, b: 26, l: 36 };
  const max = niceMax(Math.max(1, ...series.flatMap(s => s.values)));
  const x = i => m.l + (dates.length < 2 ? (W - m.l - m.r) / 2 : i * (W - m.l - m.r) / (dates.length - 1));
  const y = v => H - m.b - v / max * (H - m.t - m.b);
  const every = Math.max(1, Math.ceil(dates.length / Math.max(2, Math.floor((W - m.l - m.r) / 70))));
  let svg = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Open postings over time by role">`;
  ticks(max).forEach(t => svg += `<line class="gridline" x1="${m.l}" x2="${W - m.r}" y1="${y(t)}" y2="${y(t)}"/><text x="${m.l - 6}" y="${y(t) + 4}" text-anchor="end">${t.toLocaleString()}</text>`);
  dates.forEach((d, i) => { if (i % every === 0 || i === dates.length - 1) svg += `<text x="${x(i)}" y="${H - 8}" text-anchor="middle">${fmtShort(d)}</text>`; });
  // end labels, nudged apart only enough to avoid overlap, with a leader to the line end
  const ends = series.map(s => ({ s, y: y(s.values.at(-1)) })).sort((a, b) => a.y - b.y);
  for (let i = 1; i < ends.length; i++) ends[i].ly = Math.max(ends[i].y, (ends[i - 1].ly ?? ends[i - 1].y) + 14);
  ends[0] && (ends[0].ly = ends[0].y);
  series.forEach(s => {
    const pts = s.values.map((v, i) => `${x(i)},${y(v)}`).join(" ");
    svg += dates.length > 1 ? `<polyline fill="none" style="stroke:${s.color}" stroke-width="2" stroke-linejoin="round" stroke-linecap="round" points="${pts}"/>` : "";
    svg += `<circle cx="${x(dates.length - 1)}" cy="${y(s.values.at(-1))}" r="4" style="fill:${s.color};stroke:var(--panel)" stroke-width="2"/>`;
  });
  ends.forEach(e => svg += `<line x1="${x(dates.length - 1) + 6}" x2="${W - m.r + 6}" y1="${e.y}" y2="${e.ly}" style="stroke:var(--grid)"/>
    <text x="${W - m.r + 10}" y="${e.ly + 4}" style="fill:var(--text)">${esc(e.s.short || e.s.label)} ${e.s.values.at(-1)}</text>`);
  svg += `<line class="cross" x1="0" x2="0" y1="${m.t}" y2="${H - m.b}" style="stroke:var(--muted)" stroke-width="1" visibility="hidden"/>
    <rect x="${m.l}" y="0" width="${W - m.l - m.r}" height="${H}" fill="transparent" class="hit"/></svg>`;
  el.innerHTML = svg;
  const svgEl = el.querySelector("svg"), cross = el.querySelector(".cross");
  const move = ev => {
    const r = svgEl.getBoundingClientRect(), px = (ev.clientX - r.left) * W / r.width;
    const i = Math.max(0, Math.min(dates.length - 1, Math.round((px - m.l) / ((W - m.l - m.r) / Math.max(1, dates.length - 1)))));
    cross.setAttribute("x1", x(i)); cross.setAttribute("x2", x(i)); cross.setAttribute("visibility", "visible");
    tooltip(el, `<b>${fmtDate(dates[i])}</b>${series.map(s => tipRow(s.color, s.label, s.values[i])).join("")}`,
            (x(i) / W) * r.width, (ev.clientY - r.top));
  };
  svgEl.querySelector(".hit").addEventListener("pointermove", move);
  svgEl.querySelector(".hit").addEventListener("pointerleave", () => { cross.setAttribute("visibility", "hidden"); tooltip(el, null); });
}

function stackedColumns(el, weeks, series) {  // series: [{label,color,values}] stacked per week
  const W = Math.max(320, el.clientWidth || 600), H = 220, m = { t: 12, r: 8, b: 26, l: 36 };
  const totals = weeks.map((_, i) => series.reduce((a, s) => a + s.values[i], 0));
  const max = niceMax(Math.max(1, ...totals));
  const band = (W - m.l - m.r) / weeks.length, bw = Math.min(24, band * .6);
  const y = v => H - m.b - v / max * (H - m.t - m.b);
  const every = Math.max(1, Math.ceil(weeks.length / Math.max(2, Math.floor((W - m.l - m.r) / 60))));
  let svg = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="New postings per week by role">`;
  ticks(max).forEach(t => svg += `<line class="gridline" x1="${m.l}" x2="${W - m.r}" y1="${y(t)}" y2="${y(t)}"/><text x="${m.l - 6}" y="${y(t) + 4}" text-anchor="end">${t.toLocaleString()}</text>`);
  weeks.forEach((w, i) => {
    const cx = m.l + band * i + band / 2;
    let base = 0;
    const segs = series.map(s => ({ s, v: s.values[i] })).filter(d => d.v > 0);
    segs.forEach((d, k) => {
      const top = k === segs.length - 1, y0 = y(base), y1 = y(base + d.v), h = Math.max(0, y0 - y1 - (k ? 2 : 0));
      const yTop = y1, r = top ? Math.min(4, h / 2) : 0;
      // rounded data end on the top segment only; 2px surface gap between segments
      svg += r ? `<path style="fill:${d.s.color}" d="M${cx - bw / 2},${yTop + h} V${yTop + r} Q${cx - bw / 2},${yTop} ${cx - bw / 2 + r},${yTop} H${cx + bw / 2 - r} Q${cx + bw / 2},${yTop} ${cx + bw / 2},${yTop + r} V${yTop + h} Z"/>`
               : `<rect style="fill:${d.s.color}" x="${cx - bw / 2}" y="${yTop}" width="${bw}" height="${h}"/>`;
      base += d.v;
    });
    if (i % every === 0 || i === weeks.length - 1) svg += `<text x="${cx}" y="${H - 8}" text-anchor="middle">${fmtShort(w)}</text>`;
    svg += `<rect x="${m.l + band * i}" y="${m.t}" width="${band}" height="${H - m.t - m.b}" fill="transparent" data-i="${i}" class="hit"/>`;
  });
  el.innerHTML = svg + "</svg>";
  const svgEl = el.querySelector("svg");
  svgEl.querySelectorAll(".hit").forEach(h => {
    h.addEventListener("pointermove", ev => {
      const i = +h.dataset.i, r = svgEl.getBoundingClientRect();
      tooltip(el, `<b>Week of ${fmtDate(weeks[i])}</b>${series.map(s => tipRow(s.color, s.label, s.values[i])).join("")}
        <div class="row"><span></span><span>Total</span><span>${totals[i]}</span></div>`, ev.clientX - r.left, ev.clientY - r.top);
    });
    h.addEventListener("pointerleave", () => tooltip(el, null));
  });
}

function horizontalBars(el, rows) {  // rows: [label, value], single series
  const W = Math.max(320, el.clientWidth || 600), rowH = 26, labelW = Math.min(220, W * .42), m = { t: 4, r: 40 };
  const H = m.t + rows.length * rowH, max = Math.max(1, ...rows.map(r => r[1]));
  const x = v => v / max * (W - labelW - m.r);
  let svg = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Employers with the most new postings">`;
  rows.forEach(([label, v], i) => {
    const y0 = m.t + i * rowH, bh = 14, yb = y0 + (rowH - bh) / 2, w = Math.max(2, x(v)), r = Math.min(4, w / 2);
    const short = label.length > 30 ? label.slice(0, 29) + "…" : label;
    svg += `<text x="${labelW - 8}" y="${y0 + rowH / 2 + 4}" text-anchor="end" style="fill:var(--text)">${esc(short)}<title>${esc(label)}</title></text>
      <path style="fill:var(--pilot)" d="M${labelW},${yb} H${labelW + w - r} Q${labelW + w},${yb} ${labelW + w},${yb + r} V${yb + bh - r} Q${labelW + w},${yb + bh} ${labelW + w - r},${yb + bh} H${labelW} Z"/>
      <text x="${labelW + w + 6}" y="${y0 + rowH / 2 + 4}">${v}</text>`;
  });
  el.innerHTML = svg + "</svg>";
}

function renderTrends() {
  const jobs = state.jobs;
  if (!jobs.length) { $("trend-tiles").innerHTML = `<div class="empty">No data yet.</div>`; return; }
  const start = jobs.map(j => dayOf(j.first_seen)).sort()[0], end = today();
  const dates = dateRange(start, end);
  const colors = Object.fromEntries(ROLES.map(([k]) => [k, `var(--${k})`]));
  // open postings per day: listed on or before the day and not yet closed
  const series = ROLES.map(([k, label]) => ({ key: k, label, short: label.split(" ")[0], color: colors[k], values: dates.map(d =>
    jobs.filter(j => roleOf(j) === k && dayOf(j.first_seen) <= d && (!j.closed_at || dayOf(j.closed_at) > d)).length) }));
  const weekAgo = new Date(Date.now() - 7 * DAY).toISOString(), monthAgo = new Date(Date.now() - 30 * DAY).toISOString();
  const closed = jobs.filter(j => j.closed_at);
  const durations = closed.map(openDays).filter(d => d !== null);
  const strongOpen = jobs.filter(j => j.active && ["strong", "possible"].includes(verdictOf(j))).length;
  $("trend-tiles").innerHTML = [
    ["Open now", jobs.filter(j => j.active).length],
    ["New in the last 7 days", jobs.filter(j => j.first_seen >= weekAgo && dayOf(j.first_seen) > start).length, "excludes the first poll"],
    ["Closed in the last 7 days", closed.filter(j => j.closed_at >= weekAgo).length],
    ["Median days open", median(durations) ?? "–", durations.length ? `${durations.length} closed postings` : "none closed yet"],
    ["Open strong / possible matches", strongOpen],
  ].map(([label, value, hint]) => `<div class="tile"><div class="label">${label}</div><div class="value">${typeof value === "number" ? value.toLocaleString() : value}</div>${hint ? `<div class="hint">${hint}</div>` : ""}</div>`).join("");

  $("open-note").textContent = `Since tracking began on ${fmtDate(start)}`;
  $("open-legend").innerHTML = legendHtml(series.map(s => [s.color, s.label]));
  lineChart($("open-chart"), dates, series);
  $("open-table").innerHTML = tableHtml(["Date", ...series.map(s => s.label)], dates.map((d, i) => [fmtDate(d), ...series.map(s => s.values[i])]).reverse());

  const weeks = dateRange(weekStart(start), end).filter(d => weekStart(d) === d);
  const weekly = ROLES.map(([k, label]) => ({ label, color: colors[k], values: weeks.map(w =>
    jobs.filter(j => roleOf(j) === k && weekStart(dayOf(j.first_seen)) === w).length) }));
  $("weekly-legend").innerHTML = legendHtml(weekly.map(s => [s.color, s.label])) +
    `<span>First week includes every posting already open when tracking began</span>`;
  stackedColumns($("weekly-chart"), weeks, weekly);
  $("weekly-table").innerHTML = tableHtml(["Week of", ...weekly.map(s => s.label), "Total"],
    weeks.map((w, i) => [fmtDate(w), ...weekly.map(s => s.values[i]), weekly.reduce((a, s) => a + s.values[i], 0)]).reverse());

  const byCompany = {};
  jobs.filter(j => j.first_seen >= monthAgo).forEach(j => byCompany[j.company] = (byCompany[j.company] || 0) + 1);
  const top = Object.entries(byCompany).sort((a, b) => b[1] - a[1]).slice(0, 10);
  horizontalBars($("employers-chart"), top);
  $("employers-table").innerHTML = tableHtml(["Employer", "New postings"], Object.entries(byCompany).sort((a, b) => b[1] - a[1]));

  $("duration-table").innerHTML = closed.length ? tableHtml(["Role", "Closed postings", "Median days open", "Shortest", "Longest"],
    ROLES.map(([k, label]) => { const d = closed.filter(j => roleOf(j) === k).map(openDays).filter(v => v !== null);
      return [label, d.length, median(d) ?? "–", d.length ? Math.min(...d) : "–", d.length ? Math.max(...d) : "–"]; }))
    : `<p class="note">No postings have closed yet. This fills in as boards remove listings.</p>`;
}
