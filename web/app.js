function renderApps() {
  const apps = tracker.list();
  const counts = Object.fromEntries(STATUSES.map(([s]) => [s, 0]));
  apps.forEach(a => counts[a.status]++);
  const sent = apps.filter(a => a.applied_on).length;
  const replies = apps.filter(a => ["interview", "offer"].includes(a.status)).length;
  $("app-tiles").innerHTML = [
    ...STATUSES.slice(0, 5).map(([s, l]) => [l, counts[s], s]),
    ["Interview rate", sent ? `${Math.round(100 * replies / sent)}%` : "–", null, `${replies} of ${sent} applications`],
  ].map(([label, value, s, hint]) => `<div class="tile"><div class="label">${s ? `<span class="dot" style="background:var(--${s})"></span>` : ""}${label}</div>
     <div class="value">${value}</div>${hint ? `<div class="hint">${hint}</div>` : ""}</div>`).join("");

  const filter = $("app-filter").value;
  const shown = apps.filter(a => !filter || a.status === filter)
    .sort((a, b) => (b.applied_on || b.updated_at || "").localeCompare(a.applied_on || a.updated_at || ""));
  $("app-list").innerHTML = shown.length ? shown.map(a => {
    const job = state.byId[a.id];
    const posting = job ? (job.active ? "Posting open" : `Posting closed ${fmtDate(job.closed_at)}`) : (a.id.startsWith("manual:") ? "Added manually" : "Posting no longer tracked");
    const waited = a.applied_on && a.status === "applied" ? Math.floor((Date.now() - new Date(a.applied_on + "T12:00:00")) / DAY) : null;
    return `<article class="card app-card" data-app="${esc(a.id)}">
      <div class="app-grid">
        <div>
          <a class="title" href="${esc(a.url || "#")}" target="_blank" rel="noopener noreferrer">${esc(a.title)}</a>
          <span class="badge" style="color:var(--${a.status})">${STATUS_LABEL[a.status]}</span>
          <div class="meta">${esc(a.company)}${a.location ? ` · ${esc(a.location)}` : ""} · ${ROLE_LABEL[a.role] || ""} · ${posting}
            ${waited !== null ? ` · ${waited} day${waited === 1 ? "" : "s"} since applying` : ""}</div>
        </div>
        <div class="actions" style="margin:0">
          ${a.apply_url && a.status === "saved" && job?.active !== false ? `<a class="btn" href="${esc(a.apply_url)}" target="_blank" rel="noopener noreferrer">Apply ↗</a>` : ""}
          <button class="btn" data-remove="${esc(a.id)}" aria-label="Remove">Remove</button>
        </div>
      </div>
      <div class="app-fields">
        <label>Status ${statusSelect(a.id, a.status)}</label>
        <label>Applied on <input type="date" data-field="applied_on" value="${esc(a.applied_on || "")}"></label>
        <label>Follow up <input type="date" data-field="follow_up" value="${esc(a.follow_up || "")}"></label>
      </div>
      <textarea data-field="notes" placeholder="Notes: contact, interview date, references…">${esc(a.notes || "")}</textarea>
      ${(a.history || []).length ? `<div class="note">History: ${a.history.map(h => `${STATUS_LABEL[h.status]} ${fmtDate(h.at)}`).join(" → ")}</div>` : ""}
    </article>`;
  }).join("") : `<div class="empty">${apps.length ? "No applications with this status." :
      "No applications yet. Use <b>Track…</b> on a job card, click <b>Apply</b>, or add one manually."}</div>`;
}

