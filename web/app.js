function start(data) {
  data.jobs = (data.jobs || []).map(sanitizeJob);
  state.jobs = data.jobs; state.updated = data.updated;
  state.byId = Object.fromEntries(data.jobs.map(j => [j.id, j]));
  $("login").hidden = true; $("app").hidden = false;
  $("lock").hidden = vault.plaintext;
  $("updated").textContent = `Last polled ${data.updated ? new Date(data.updated).toLocaleString() : "never"} · ${data.jobs.filter(j => j.active).length} open postings`
    + (vault.plaintext ? " · UNENCRYPTED DEVELOPMENT BUILD" : "");
  [...new Set(data.jobs.map(j => j.company))].sort()
    .forEach(c => $("company").insertAdjacentHTML("beforeend", `<option>${esc(c)}</option>`));
  return vault.load().then(() => {
    tracker.apps = {};
    tracker.merge(Object.values(vault.data.applications || {}));
    sync.cfg = vault.data.sync && sync.valid(vault.data.sync) ? vault.data.sync : null;
    renderAll();
    showTab(store.get("tab", "jobs"));
    sync.pull();
  });
}

function showLogin(blob) {
  $("login").hidden = false; $("app").hidden = true;
  $("password").focus();
  $("login-form").onsubmit = async e => {
    e.preventDefault();
    const button = $("login-form").querySelector("button");
    button.disabled = true; button.textContent = "Unlocking…"; $("login-error").hidden = true;
    try {
      const key = await vault.derive($("password").value, blob.salt, blob.iter || 600000);
      const data = await vault.decrypt(blob, key);  // AES-GCM: throws on a wrong password
      vault.key = key;
      $("password").value = "";
      if ($("remember").checked) await keystore.put({ key, salt: blob.salt });
      await start(data);
    } catch {
      await new Promise(r => setTimeout(r, 600));
      $("login-error").hidden = false;
    } finally { button.disabled = false; button.textContent = "Unlock"; }
  };
}

$("lock").onclick = async () => {
  await keystore.clear();
  vault.key = null; tracker.apps = {}; sync.cfg = null;
  location.reload();
};

(async () => {
  try {
    const res = await fetch("jobs.enc.json", { cache: "no-store" });
    if (res.ok) {
      const blob = await res.json();
      vault.salt = blob.salt; vault.iter = blob.iter || 600000;
      const remembered = await keystore.get();
      if (remembered && remembered.salt === blob.salt) {
        try { vault.key = remembered.key; return await start(await vault.decrypt(blob)); }
        catch { vault.key = null; await keystore.clear(); }  // password changed since this device was remembered
      }
      return showLogin(blob);
    }
    const dev = await fetch("jobs.json", { cache: "no-store" });  // local development build only
    if (!dev.ok) throw new Error(`no job data (HTTP ${res.status})`);
    vault.plaintext = true;
    await start(await dev.json());
  } catch (e) {
    $("login").hidden = false; $("login-form").hidden = true;
    $("login-error").hidden = false; $("login-error").textContent = `Could not load job data: ${e.message}`;
  }
})();
