function renderJobs() {
  const q = $("q").value.trim().toLowerCase(), company = $("company").value, role = $("role").value;
  const visible = state.jobs.filter(j => ($("closed").checked || j.active) && (!role || roleOf(j) === role)
                                         && !($("hide-tracked").checked && tracker.get(j.id)));
  const counts = Object.fromEntries(VERDICTS.map(v => [v, 0]));
  visible.forEach(j => counts[verdictOf(j)]++);
  $("stats").innerHTML = [["", "All", visible.length], ...VERDICTS.map(v => [v, v, counts[v]])]
    .map(([v, label, n]) => `<div class="stat ${state.verdict === v ? "on" : ""}" data-v="${v}"
       style="${v ? `color:var(--${v})` : ""}"><b>${n}</b>${label}</div>`).join("");

  const jobs = visible.filter(j => (!state.verdict || verdictOf(j) === state.verdict) && (!company || j.company === company)
    && (!q || `${j.title} ${j.company} ${j.location}`.toLowerCase().includes(q)));
  jobs.sort($("sort").value === "score"
    ? (a, b) => (b.evaluation?.score ?? -1) - (a.evaluation?.score ?? -1) || b.first_seen.localeCompare(a.first_seen)
    : (a, b) => b.first_seen.localeCompare(a.first_seen));

  $("list").innerHTML = jobs.length ? jobs.map(j => {
    const ev = j.evaluation, v = verdictOf(j), app = tracker.get(j.id);
    return `<article class="job ${j.active ? "" : "closed"}">
      <div class="top">
        <div class="score" style="background:var(--${v})">${ev ? ev.score : "–"}</div>
        <div class="info">
          <a class="title" href="${esc(j.url)}" target="_blank" rel="noopener noreferrer">${esc(j.title)}</a>
          <span class="badge" style="color:var(--${v})">${v}</span>
          ${app ? `<span class="badge" style="color:var(--${app.status})">${STATUS_LABEL[app.status]}</span>` : ""}
          ${j.active ? "" : `<span class="badge" style="color:var(--muted)">closed ${fmtDate(j.closed_at)}</span>`}
          <div class="meta">${esc(j.company)} · ${esc(j.location || "Location n/a")} · ${ROLE_LABEL[roleOf(j)]} ·
            found ${fmtDate(j.first_seen)} · ${sourcesLine(j)}</div>
        </div>
      </div>
      ${ev ? `<p class="summary">${esc(ev.summary)}</p>
        <details><summary>Requirement breakdown</summary><div class="cols">
          ${list("Dealbreakers", ev.dealbreakers)}${list("Missing", ev.missing)}${list("You meet", ev.met)}
        </div></details>` : ""}
      <div class="actions">
        ${j.active && j.apply_url ? `<a class="btn primary" href="${esc(j.apply_url)}" target="_blank" rel="noopener noreferrer"
            data-apply="${esc(j.id)}">Apply ↗</a>` : ""}
        ${j.url ? `<a class="btn" href="${esc(j.url)}" target="_blank" rel="noopener noreferrer">View posting</a>` : ""}
        ${statusSelect(j.id, app?.status)}
      </div>
    </article>`;
  }).join("") : `<div class="empty">No postings match these filters.</div>`;
}

