function sanitizeJob(j) {  // jobs.json is generated by the poller, but its text comes from scraped pages
  const ev = j.evaluation && pick(j.evaluation.verdict, VERDICTS, null) ? {
    ...j.evaluation, score: Math.max(0, Math.min(100, Number(j.evaluation.score) || 0)),
    summary: str(j.evaluation.summary, 1000),
    met: [].concat(j.evaluation.met || []).map(x => str(x, 300)),
    missing: [].concat(j.evaluation.missing || []).map(x => str(x, 300)),
    dealbreakers: [].concat(j.evaluation.dealbreakers || []).map(x => str(x, 300)),
  } : null;
  return { ...j, id: str(j.id), title: str(j.title), company: str(j.company), location: str(j.location),
    url: safeUrl(j.url), apply_url: safeUrl(j.apply_url) || safeUrl(j.url), role: pick(j.role, ROLE_KEYS, "ground"),
    evaluation: ev, also_listed: (j.also_listed || []).map(l => ({ source: str(l.source, 30), url: safeUrl(l.url) })).filter(l => l.url) };
}

function sanitizeApp(a) {  // applications come from this browser, an imported file, or the sync repo
  if (!a || !a.id) return null;
  const base = { id: str(a.id, 300), updated_at: str(a.updated_at, 40) };
  if (a.deleted) return { ...base, deleted: true };
  return { ...base, company: str(a.company), title: str(a.title), location: str(a.location),
    url: safeUrl(a.url), apply_url: safeUrl(a.apply_url), role: pick(a.role, ROLE_KEYS, "ground"),
    status: pick(a.status, STATUS_KEYS, "saved"), applied_on: isoDay(a.applied_on), follow_up: isoDay(a.follow_up),
    notes: str(a.notes, 5000),
    history: (a.history || []).filter(h => STATUS_KEYS.includes(h.status)).map(h => ({ status: h.status, at: str(h.at, 40) })) };
}

const b64 = {
  enc(buf) { const bytes = new Uint8Array(buf); let out = ""; for (let i = 0; i < bytes.length; i += 0x8000) out += String.fromCharCode(...bytes.subarray(i, i + 0x8000)); return btoa(out); },
  dec(s) { return Uint8Array.from(atob(s), c => c.charCodeAt(0)); },
};

/* Same format and KDF as jobhunter/crypto.py: PBKDF2-SHA256 -> AES-256-GCM. */
const vault = {
  key: null, salt: null, iter: 600000, plaintext: false, data: { applications: {}, sync: null }, pending: Promise.resolve(),
  async derive(password, saltB64, iterations) {
    const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(password), "PBKDF2", false, ["deriveKey"]);
    return crypto.subtle.deriveKey({ name: "PBKDF2", hash: "SHA-256", salt: b64.dec(saltB64), iterations }, base,
                                   { name: "AES-GCM", length: 256 }, false, ["encrypt", "decrypt"]);  // non-extractable
  },
  async decrypt(blob, key = this.key) {
    const pt = await crypto.subtle.decrypt({ name: "AES-GCM", iv: b64.dec(blob.iv) }, key, b64.dec(blob.ct));
    return JSON.parse(new TextDecoder().decode(pt));
  },
  async encrypt(obj) {
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv }, this.key, new TextEncoder().encode(JSON.stringify(obj)));
    return { v: 1, kdf: "PBKDF2-SHA256", iter: this.iter, salt: this.salt, iv: b64.enc(iv), ct: b64.enc(ct) };
  },
  async load() {
    if (this.plaintext) { this.data = store.get("dev-vault", this.data); }
    else {
      const blob = store.get("vault", null);
      if (blob && blob.salt === this.salt) {
        try { this.data = await this.decrypt(blob); } catch { /* saved under an older password: start fresh */ }
      }
    }
    // migrate data saved unencrypted by earlier versions of this page, then delete it
    const legacyApps = store.get("applications", null), legacySync = store.get("sync", null);
    if (legacyApps) Object.assign(this.data.applications, legacyApps);
    if (legacySync && !this.data.sync) this.data.sync = legacySync;
    store.del("applications"); store.del("sync");
    if (legacyApps || legacySync) this.save();
  },
  save() {  // serialized so an older write can't land after a newer one
    this.pending = this.pending.then(async () => {
      if (this.plaintext) store.set("dev-vault", this.data);
      else if (this.key) store.set("vault", await this.encrypt(this.data));
    }).catch(() => {});
  },
};

